/**
 * The engine's module format. A module is a self-contained package that merges into the card:
 * its values (a fragment of the variable sheet), lorebook rules, regex, and a screen (HTML, CSS and
 * JavaScript that runs against the engine core) mounted in a slot. Modules can be saved to a library
 * shared across projects and moved between machines as pack files.
 */
import type { EngineVar } from "../sheet";

/**
 * Where a module's screen goes:
 * - panel: a section of the status panel under each reply,
 * - overlay: a screen over the chat, opened from a hub button above the input box,
 * - message: an inline block wherever a message holds `<cf-module id="…"/>`,
 * - script: no screen; only its script part runs.
 */
export type Slot = "panel" | "overlay" | "message" | "script";

export const SLOTS: Record<Slot, { label: string; help: string }> = {
  panel: { label: "Status panel", help: "A section of the status panel under each reply." },
  overlay: { label: "Hub screen", help: "Opens over the chat from a button above the input box." },
  message: { label: "Inline block", help: 'Shows inside a message wherever it holds <cf-module id="…"/>.' },
  script: { label: "Script only", help: "No screen: only its script part runs, like a rule engine." },
};

export interface ModuleRule {
  /** The lorebook entry's name. */
  comment: string;
  content: string;
  /** Always sent; otherwise sent when a key appears in the chat. */
  constant: boolean;
  keys: string[];
  /** Sent at this depth in the chat, or with the character's description when unset. */
  depth?: number;
  order: number;
}

export interface ModuleRegex {
  name: string;
  /** "/pattern/flags" as SillyTavern writes it. */
  find: string;
  replace: string;
  /** Runs on the AI's replies, the player's messages, or both. */
  ai: boolean;
  user: boolean;
  /** Changes only what the player sees, or only what the model is sent. */
  only: "display" | "prompt" | "both";
  /** Skips the latest messages: 2 leaves the last two alone. */
  minDepth?: number;
}

export const CORE_KINDS = ["time", "settings", "creator", "phone", "title", "menu", "people", "events", "journal", "notify", "life", "school", "routes", "choices", "hero", "inventory", "quests", "map", "combat", "ship", "case", "stage"] as const;
export type CoreKind = (typeof CORE_KINDS)[number];

/** Where a forked module came from: a copy of a built-in that became the card's own code. */
export interface ModuleFork {
  /** The built-in it was copied from. */
  core: CoreKind;
  /** The original's settings, to go back to it. */
  settings: Record<string, unknown>;
  /** A fingerprint of CardForge's code for it when it was forked, to tell when CardForge updated it. */
  code: string;
  /** One phone app forked on its own: the app's id. */
  piece?: string;
  at: number;
}

export interface EngineModule {
  /** Unique within a card; also the id in `<cf-module id="…"/>` and `CF.open("…")`. */
  id: string;
  name: string;
  version: string;
  description: string;
  slot: Slot;
  /** The hub button's label, for an overlay module. */
  button?: string;
  tags: string[];
  /** Ids of modules this one needs. */
  requires: string[];
  /** A built-in module, generated by CardForge from its settings. */
  core?: CoreKind;
  /** A copy of a built-in, now the card's own. */
  fork?: ModuleFork;
  enabled: boolean;
  /** Its values: groups of the game state it adds. */
  vars: EngineVar[];
  rules: ModuleRule[];
  regex: ModuleRegex[];
  /** The screen. `js` runs with CF (the core), app (this screen) and root (its element). */
  html: string;
  css: string;
  js: string;
  /** Runs once in the card's script when the chat opens, with CF, settings and hooks. */
  script: string;
  /** Options the module's code reads. */
  settings: Record<string, unknown>;
  /** Living screens: content the model writes during play, in the background (see live.ts). */
  live?: LiveFeed[];
}

/** How a living screen's content is written: the co-writer's notes for the background model. */
export interface LivePack {
  /** Whose voice: "Mina texting: lowercase, quick, teasing, emoji only when flustered". */
  voice: string;
  /** The mood and attitude: "warm, a little jealous of {{user}}'s friends". */
  tone: string;
  /** The shape of one item: "a text message", "a headline, a dash, one sentence". */
  format: string;
  /** How long one item is: "one to two short lines". */
  length: string;
}

/**
 * A living screen: after a reply, a silent background generation writes a few new items (texts,
 * posts, headlines) in the pack's voice. Items are kept on the reply's message variables, per swipe,
 * so a reroll gets its own and going back to a swipe brings its items back.
 */
export interface LiveFeed {
  /** Unique within the card; screens read it with app.live(id). */
  id: string;
  name: string;
  /** Off by default: each run costs tokens on the player's API. */
  enabled: boolean;
  pack: LivePack;
  /** Who usually writes the items ("Mina"); empty when nobody does (news). */
  from: string;
  /** Items one run writes, 1 to 5. */
  count: number;
  /** Runs after every Nth reply (1 = each reply); 0 runs only when an `on` value changes. */
  every: number;
  /** Values whose change makes it run, like "Mina.Affection". */
  on: string[];
  /** Chat messages the background call reads, 2 to 30. */
  history: number;
  /** Items the screens see, newest last, 1 to 100. */
  keep: number;
  /** A list value the items are also added to as "From: text" lines (Phone.Texts), so the story and the built-in phone see them. */
  into: string;
  /** Lines used when the generation fails, so the screen still moves. */
  fallback: string[];
}

/** The built-in a module is, or is a whole fork of (a forked phone app is a module of its own). */
export const kindOf = (m: EngineModule): CoreKind | undefined => m.core ?? (m.fork && !m.fork.piece ? m.fork.core : undefined);

export const PACK_FORMAT = "cardforge-module-pack";

export interface ModulePack {
  format: typeof PACK_FORMAT;
  version: 1;
  modules: EngineModule[];
}
